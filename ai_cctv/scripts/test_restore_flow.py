import os
import sys
import shutil
import zipfile
import subprocess
from pathlib import Path

repo_root = Path(__file__).resolve().parent.parent
restore_test_dir = repo_root / "clean_restore_test" / "restore module" / "ai_cctv_detection"

if restore_test_dir.exists():
    shutil.rmtree(restore_test_dir)
restore_test_dir.mkdir(parents=True, exist_ok=True)

zip_p = repo_root / "dist" / "ai_cctv_detection_runtime_20261025.zip"
print("========================================================")
print(" TESTING RESTORATION FLOW & RETRAINING TOOLING")
print(f" Target Directory: {restore_test_dir}")
print(f" Package File:    {zip_p}")
print("========================================================\n")

print("[Step 1/4] Extracting runtime package...")
with zipfile.ZipFile(zip_p, "r") as zf:
    zf.extractall(restore_test_dir)
print("  [OK] Runtime package extracted.")

archive_dir = repo_root / "_archive_training_data"
assert archive_dir.exists(), f"Archive directory not found: {archive_dir}"

print(f"\n[Step 2/4] Running restore_training_data.bat '{archive_dir}'...")
restore_bat = restore_test_dir / "restore_training_data.bat"

cmd_str = f'cmd.exe /c "\"{restore_bat}\" \"{archive_dir}\""'
res = subprocess.run(
    cmd_str,
    cwd=str(restore_test_dir),
    capture_output=True,
    text=True
)

print(res.stdout)
if res.returncode != 0:
    print("[ERROR] Restoration failed:", res.stderr)
    sys.exit(1)
print("  [OK] Restoration script completed successfully.")

print("\n[Step 3/4] Verifying restored directory tree...")
for sub in ["data", "data_raw", "runs"]:
    p = restore_test_dir / sub
    file_count = len([f for f in p.rglob("*") if f.is_file()])
    print(f"  Restored {sub}/: {file_count} files verified.")
    assert p.exists() and file_count > 0, f"Restored {sub} missing or empty"

print("\n[Step 4/4] Executing build_dataset smoke test on restored footage...")
python_exe = repo_root / ".venv" / "Scripts" / "python.exe"
build_tool = restore_test_dir / "tools" / "build_dataset.py"
smoke_out = restore_test_dir / "data_smoke_test"

build_proc = subprocess.run(
    [str(python_exe), str(build_tool), str(restore_test_dir / "data_raw" / "real"), str(restore_test_dir / "data_raw" / "fake"), "--output-dir", str(smoke_out), "--fps", "1.0"],
    capture_output=True,
    text=True
)

print(build_proc.stdout)
assert smoke_out.exists(), "smoke_out directory not created"
manifest_p = smoke_out / "manifest.json"
assert manifest_p.exists(), "manifest.json not created in smoke_out"
print(f"  [OK] manifest.json created at {manifest_p}")

# Test calibrate with restored data
calibrate_tool = restore_test_dir / "tools" / "calibrate.py"
temp_calib_yaml = restore_test_dir / "temp_calibration.yaml"
calib_proc = subprocess.run(
    [str(python_exe), str(calibrate_tool), "--model", str(restore_test_dir / "models" / "best.pt"), "--val-dir", str(restore_test_dir / "data" / "val"), "--output-config", str(temp_calib_yaml)],
    capture_output=True,
    text=True
)
print("Calibrate tool test output:")
print(calib_proc.stdout)
assert temp_calib_yaml.exists(), "temp_calibration.yaml was not generated by calibrate.py"
print("  [OK] calibrate.py successfully generated calibration parameters from restored data.")

# Clean up smoke test artifacts without touching any real weights
shutil.rmtree(smoke_out, ignore_errors=True)
if temp_calib_yaml.exists():
    temp_calib_yaml.unlink()
print("  [OK] Smoke test output safely cleaned up. Real models were NOT overwritten.")

print("\n========================================================")
print(" RESTORE FLOW & RETRAINING TOOLING: 100% VERIFIED PASS!")
print("========================================================")
