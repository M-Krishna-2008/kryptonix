#!/usr/bin/env python3
"""
Executes Step 1 diagnosis:
- Prepares 3 genuine voice recordings in original format
- Converts the 3 genuine recordings to MP3 @ 128 kbps and 64 kbps
- Prepares 3 synthetic TTS recordings
- Runs debug_scores on all recordings and produces the comparison table.
"""

import sys
import urllib.request
from pathlib import Path
import av
import pyttsx3
import soundfile as sf
import numpy as np

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from tools.debug_scores import debug_file

DIAG_DIR = PROJECT_ROOT / "data_diagnosis"
DIAG_DIR.mkdir(parents=True, exist_ok=True)


def download_genuine_samples():
    urls = {
        "genuine_1.flac": "https://huggingface.co/datasets/Narsil/asr_dummy/resolve/main/1.flac",
        "genuine_2.flac": "https://huggingface.co/datasets/Narsil/asr_dummy/resolve/main/2.flac",
        "genuine_3.flac": "https://huggingface.co/datasets/Narsil/asr_dummy/resolve/main/3.flac",
    }
    paths = []
    for fname, url in urls.items():
        dst = DIAG_DIR / fname
        if not dst.is_file():
            print(f"Downloading genuine sample: {fname}...")
            urllib.request.urlretrieve(url, str(dst))
        paths.append(dst)
    return paths


def generate_tts_samples():
    texts = {
        "tts_1_sapi.wav": "This is synthetic speech test clip one generated by the local speech synthesizer for forensic analysis.",
        "tts_2_sapi.wav": "Digital evidence authentication platform is examining acoustic voice frequencies for artificial generation.",
        "tts_3_sapi.wav": "The prosecution presented an audio recording claiming it contains genuine human statements regarding the contract.",
    }
    engine = pyttsx3.init()
    paths = []
    for fname, text in texts.items():
        dst = DIAG_DIR / fname
        if not dst.is_file():
            print(f"Generating TTS sample: {fname}...")
            engine.save_to_file(text, str(dst))
            engine.runAndWait()
        paths.append(dst)
    return paths


def convert_to_mp3(src_path: Path, dst_path: Path, bitrate_kbps: int):
    """Encodes input audio to MP3 at target bitrate using PyAV."""
    if dst_path.is_file():
        return
    in_container = av.open(str(src_path))
    in_stream = in_container.streams.audio[0]

    out_container = av.open(str(dst_path), mode="w", format="mp3")
    # Resample to 16kHz mono or maintain rate
    sample_rate = in_stream.rate or 16000
    out_stream = out_container.add_stream("mp3", rate=sample_rate)
    out_stream.bit_rate = bitrate_kbps * 1000

    resampler = av.AudioResampler(
        format="s16p",
        layout="mono",
        rate=sample_rate,
    )

    for frame in in_container.decode(in_stream):
        resampled_frames = resampler.resample(frame)
        for rf in resampled_frames:
            for packet in out_stream.encode(rf):
                out_container.mux(packet)

    for packet in out_stream.encode():
        out_container.mux(packet)

    out_container.close()
    in_container.close()
    print(f"Encoded {dst_path.name} ({bitrate_kbps} kbps)")


def run_diagnosis():
    print("================================================================")
    print("STEP 1: GATHERING AND PREPARING TEST SAMPLES")
    print("================================================================")
    genuine_orig = download_genuine_samples()
    tts_clips = generate_tts_samples()

    # Convert genuine to MP3 @ 128k and 64k
    genuine_128k = []
    genuine_64k = []
    for g in genuine_orig:
        p_128 = DIAG_DIR / f"{g.stem}_128k.mp3"
        p_64 = DIAG_DIR / f"{g.stem}_64k.mp3"
        convert_to_mp3(g, p_128, 128)
        convert_to_mp3(g, p_64, 64)
        genuine_128k.append(p_128)
        genuine_64k.append(p_64)

    all_files = [
        ("GENUINE (ORIGINAL)", genuine_orig),
        ("GENUINE (MP3 128k)", genuine_128k),
        ("GENUINE (MP3 64k)", genuine_64k),
        ("SYNTHETIC (TTS)", tts_clips),
    ]

    results = []

    print("\n================================================================")
    print("RUNNING DIAGNOSTIC SCORING ON ALL FILES")
    print("================================================================")
    for category, file_list in all_files:
        for fpath in file_list:
            res = debug_file(fpath)
            res["category"] = category
            results.append(res)

    print("\n" + "=" * 90)
    print("STEP 1 DIAGNOSTIC SUMMARY TABLE")
    print("=" * 90)
    print(f"{'Category':<22} {'File':<22} {'Duration':<10} {'Median Logit':<14} {'Min Logit':<12} {'Verdict':<20}")
    print("-" * 90)
    for r in results:
        dur_str = f"{r.get('duration', 0.0):.2f}s"
        med_str = f"{r.get('median'):.4f}" if r.get("median") is not None else "N/A"
        min_str = f"{r.get('min'):.4f}" if r.get("min") is not None else "N/A"
        verdict_str = r.get("verdict", "N/A")
        print(f"{r['category']:<22} {r['file']:<22} {dur_str:<10} {med_str:<14} {min_str:<12} {verdict_str:<20}")
    print("=" * 90)


if __name__ == "__main__":
    run_diagnosis()
